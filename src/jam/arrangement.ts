// An arrangement is plain data: what to play, not how it sounds. The rule-based generator
// below makes one from style/key/tempo; later an AI route can return the same shape.

import { STYLE_BY_ID, StyleDef } from "./styles";
import { KEY_NAMES, Mode, noteToPc, parseChord, romanToChord } from "./theory";
import { hashString, rand } from "./rng";
import type { EnergyMode } from "./dynamics";

export type PartId = "drums" | "bass" | "guitar" | "keys";

export interface ChordSlot {
  chord: string;
  beats: number;
}

export interface Arrangement {
  version: 1;
  style: string;
  key: string; // "A", "Eb" …
  mode: Mode;
  tempo: number;
  chords: ChordSlot[];
  parts: Record<PartId, boolean>;
  seed: number;
  source: "rules" | "ai" | "user";
  /** which preset progression of the style, when generated by rules */
  progressionIndex?: number;
  /** how the band's intensity moves across loop passes (default: evolving song sections) */
  energy?: EnergyMode;
  /** drum kit; "auto" (default) uses the style's */
  kit?: "auto" | "modern" | "vintage" | "brushes";
}

export interface GenerateOptions {
  style: string;
  key: string;
  mode?: Mode;
  tempo?: number;
  seed?: number;
  progressionIndex?: number;
}

export function progressionToChords(tokens: string, keyPc: number, mode: Mode, beatsPerBar: number): ChordSlot[] {
  const out: ChordSlot[] = [];
  for (const bar of tokens.trim().split(/\s+/)) {
    const pieces = bar.split("|");
    const each = beatsPerBar / pieces.length;
    for (const p of pieces) out.push({ chord: romanToChord(p, keyPc, mode), beats: each });
  }
  return out;
}

export function styleProgressions(style: StyleDef, mode: Mode): string[] {
  const list = style.progressions[mode];
  return list.length ? list : style.progressions[mode === "major" ? "minor" : "major"];
}

export function generateArrangement(opts: GenerateOptions): Arrangement {
  const style = STYLE_BY_ID[opts.style] ?? STYLE_BY_ID.rock;
  const keyPc = noteToPc(opts.key) ?? 0;
  const mode = opts.mode ?? style.mode;
  const seed = opts.seed ?? hashString(`${style.id}|${opts.key}|${mode}|${Date.now()}`);
  const progs = styleProgressions(style, mode);
  const index =
    opts.progressionIndex !== undefined && progs[opts.progressionIndex] ? opts.progressionIndex : Math.floor(rand(seed, 0, 0, "progression") * progs.length);
  const tempo = Math.round(Math.min(style.tempo.max, Math.max(style.tempo.min, opts.tempo ?? style.tempo.default)));
  return {
    version: 1,
    style: style.id,
    key: KEY_NAMES[keyPc],
    mode,
    tempo,
    chords: progressionToChords(progs[index], keyPc, mode, style.meter.beats),
    parts: { ...style.parts },
    seed,
    source: "rules",
    progressionIndex: index,
  };
}

/** Replace the chords with user-typed symbols (one per bar). Unknown symbols are dropped. */
export function withCustomChords(arr: Arrangement, symbols: string[]): Arrangement {
  const style = STYLE_BY_ID[arr.style];
  const chords = symbols.filter((c) => parseChord(c)).map((chord) => ({ chord, beats: style.meter.beats }));
  return chords.length ? { ...arr, chords, source: "user", progressionIndex: undefined } : arr;
}

export const totalBeats = (arr: Arrangement) => arr.chords.reduce((n, c) => n + c.beats, 0);
